#!/usr/bin/env python3
"""Lists the tests that may enforce a shadow setting: a value of the content written down in the test.

The rule ("Test the behaviour against the setting, not a copy of it", `docs/rust_coding_rules.md`):
a test reads the setting from the shipped rules and checks that the game does what it says; it
does not assert a cost, a stat, a count or a list that it typed in from the content.

What it does:
  * Reads every `.rs` file under `crates/` (not `f4x-ai-ref`) and finds each `#[test]` function
    (the parser of `imaginary_tests.py`).
  * Flags a test that reads the shipped content (`shipped()`, `rules.units`, `content.rules`, ...)
    and has an `assert` with a number other than 0 and 1 in it.
  * Writes the list, by crate and file with the line of each test and its first such assert, to
    `docs/tests-on-shadow-settings.md` (`--out` for another file).

It is a text search: most rows are a fixed number used as the *input* of a scenario (a unit to spawn,
a position), which is no shadow setting. Treat the list as the worksheet to read, not as the verdict;
the number falls as tests are replaced and as the survivors are judged fine.
"""

import argparse
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import imaginary_tests as it  # noqa: E402

DEFAULT_OUT = "docs/tests-on-shadow-settings.md"

READS_CONTENT = re.compile(
    r"\b(shipped\(\)|rules\.(units|buildings|spells|races|abilities|items|heroes|retorts)"
    r"|content\.rules|\.def\(|unit_def|building_def|spell_def|race_def)"
)
ASSERT = re.compile(r"assert(?:_eq|_ne)?!\(([^;]*?)\);", re.S)
NUMBER = re.compile(r"(?<![\w.\[])-?\d+(?:\.\d+)?(?![\w.\]])")
PLAIN = ("0", "1", "-1")


def crate_of(path: str) -> str:
    return path.split(os.sep)[1]


def candidates() -> tuple[list[tuple[str, str, int, str]], int]:
    """(file, test, line, first assert with a number) for each flagged test, and the test count."""
    found, total = [], 0
    for path in it.rust_files():
        for fn in it.parse_functions(path):
            if not fn.is_test:
                continue
            total += 1
            if not READS_CONTENT.search(fn.body):
                continue
            for match in ASSERT.finditer(fn.body):
                if any(n not in PLAIN for n in NUMBER.findall(match.group(0))):
                    found.append((path, fn.name, fn.line, re.sub(r"\s+", " ", match.group(0))[:100]))
                    break
    return found, total


def render(found: list[tuple[str, str, int, str]], total: int) -> str:
    per_crate: dict[str, int] = {}
    for path, *_ in found:
        per_crate[crate_of(path)] = per_crate.get(crate_of(path), 0) + 1
    lines = [
        "# Tests that may enforce a shadow setting",
        "",
        "Generated by `scripts/shadow_tests.py`; do not edit by hand, fix the tests and run it again.",
        "",
        "The rule (`docs/rust_coding_rules.md`, \"Test the behaviour against the setting, not a copy of",
        "it\"): a test reads the setting from the shipped rules and checks the game does what it says.",
        "It is a text search for a test that reads the content and asserts a number, so most rows are a",
        "number used as the input of a scenario (no shadow setting); read each row's assert.",
        "",
        f"**{len(found)} of {total} tests.**",
        "",
        "| Crate | Tests |",
        "|---|---|",
    ]
    lines += [f"| `{c}` | {n} |" for c, n in sorted(per_crate.items(), key=lambda kv: (-kv[1], kv[0]))]
    current = None
    for path, name, line, text in sorted(found):
        if path != current:
            current = path
            lines += ["", f"## `{path}`", "", "| Test | Line | First assert with a number |", "|---|---|---|"]
        lines.append(f"| `{name}` | {line} | `{text.replace('|', '/')}` |")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--out", default=DEFAULT_OUT, help="the file to write (default: %(default)s)")
    args = parser.parse_args()
    if not os.path.isdir(it.CRATES):
        sys.exit("run it from the repository root")
    found, total = candidates()
    with open(args.out, "w", encoding="utf8") as handle:
        handle.write(render(found, total))
    print(f"{len(found)} of {total} tests listed in {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
